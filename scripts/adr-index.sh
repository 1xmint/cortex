#!/usr/bin/env bash
# Generates docs/adr/README.md from the ADR files. CI fails if the committed
# index differs from what this prints, so the index cannot go stale.
set -euo pipefail
cd "$(dirname "$0")/../docs/adr"

{
  echo "# Architecture decision records"
  echo
  echo "Generated by \`scripts/adr-index.sh\`. Do not edit by hand."
  echo
  echo "| ADR | Title | Status |"
  echo "|---|---|---|"
  for f in [0-9][0-9][0-9][0-9]-*.md; do
    [ "$f" = "0000-template.md" ] && continue
    num="${f%%-*}"
    title="$(head -n1 "$f" | sed -E 's/^# [0-9]{4}\. //')"
    status="$(grep -m1 '^Status:' "$f" | sed -E 's/^Status: //')"
    echo "| [$num]($f) | $title | $status |"
  done
} > README.md
